        private readonly IWebHostEnvironment _environment;

        public ReviewMetricTrackerExcelGeneratorService(
            IWebHostEnvironment environment)
        {
            _environment = environment;
        }

        public MemoryStream GenerateReviewMetricTrackerExcel(
            ReviewMetricTrackerReportDto report)
        {
            var templatePath = Path.Combine(
                _environment.ContentRootPath,
                "Templates",
                "Report",
                "ReviewMetricTracker_API_Template.xlsx"
            );

            if (!File.Exists(templatePath))
            {
                throw new FileNotFoundException(
                    "Review Metric Tracker Excel template was not found.",
                    templatePath
                );
            }

            using var workbook =
                new XLWorkbook(templatePath);

            var worksheet =
                workbook.Worksheet("ReviewMetricTracker");

            PopulateReportInformation(
                worksheet,
                report
            );

            PopulateRows(
                worksheet,
                report
            );

            var stream = new MemoryStream();

            workbook.SaveAs(stream);

            stream.Position = 0;

            return stream;
        }


      private void PopulateReportInformation(
          IXLWorksheet worksheet,
          ReviewMetricTrackerReportDto report)
      {
        var filters = report.Filters;

        // A1 - Generated by username and date
        var generatedBy = filters.GeneratedByUser ?? string.Empty;

        var generationDate = filters.GenerationDate;

        var dateText = generationDate == DateTime.MinValue
            ? string.Empty
            : generationDate.ToString("dd/MM/yyyy");

        worksheet.Cell("A1").Value =
            $"Generated by {generatedBy} on {dateText}";

        // Filter values
        worksheet.Cell("B3").Value =
            string.Join(", ", filters.ContractPerformanceManager);

        worksheet.Cell("B4").Value =
            string.Join(", ", filters.ProgramLeader);

        worksheet.Cell("B5").Value =
            string.Join(", ", filters.GlobalExecutionLeader);

        worksheet.Cell("B6").Value =
            string.Join(", ", filters.Program);

        worksheet.Cell("B7").Value =
            FormatDateRange(filters);

        worksheet.Cell("B8").Value =
            string.Join(", ", filters.ReportingYears);

        worksheet.Cell("B9").Value =
            string.Join(", ", filters.Quarters);
    }



