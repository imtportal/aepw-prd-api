private void PopulateRows(
    IXLWorksheet worksheet,
    ReviewMetricTrackerReportDto report)
    {
      const int templateRow = 12;

      // Check whether data is available
      if (report.Data == null || !report.Data.Any())
      {
        worksheet.Cell(templateRow, 1).Value =
            "No data available for the selected filters";

        // Merge cells A12:H12 to display the message clearly
        worksheet.Range(templateRow, 1, templateRow, 8).Merge();

        worksheet.Cell(templateRow, 1).Style.Alignment.Horizontal =
            XLAlignmentHorizontalValues.Center;

        worksheet.Cell(templateRow, 1).Style.Alignment.Vertical =
            XLAlignmentVerticalValues.Center;

        worksheet.Cell(templateRow, 1).Style.Font.Bold = true;

        return;
      }

      int currentRow = templateRow;

      foreach (var item in report.Data)
      {
        if (currentRow != templateRow)
        {
          worksheet.Row(templateRow)
              .CopyTo(worksheet.Row(currentRow));
        }

        worksheet.Cell(currentRow, 1).Value = item.IMId;
        worksheet.Cell(currentRow, 2).Value = item.PIN;
        worksheet.Cell(currentRow, 3).Value = item.ProjectTitle;
        worksheet.Cell(currentRow, 4).Value = item.ReportingPeriod;
        worksheet.Cell(currentRow, 5).Value = item.ProjectStatus;
        worksheet.Cell(currentRow, 6).Value = item.Topic;

        var applicableMetrics = new[]
        {
            item.TopLevelMetric,
            item.L1Metric
        }
        .Where(x => !string.IsNullOrWhiteSpace(x))
        .Distinct();

        worksheet.Cell(currentRow, 7).Value =
            string.Join(", ", applicableMetrics);

        worksheet.Cell(currentRow, 8).Value =
            string.IsNullOrWhiteSpace(item.RecordStatus)
                ? "N/A"
                : item.RecordStatus;

        currentRow++;
      }
    }


    private string FormatDateRange(
   ReviewMetricTrackerFiltersDto filters)
    {
      if (!filters.StartDate.HasValue ||
          !filters.EndDate.HasValue)
      {
        return string.Empty;
      }

      return $"{filters.StartDate.Value:dd/MM/yyyy} - " +
             $"{filters.EndDate.Value:dd/MM/yyyy}";
    }

    private string GetRecordStatus(ReviewMetricTrackerDataDto item)
        {
            if (item.Approval == null)
            {
                return "N/A";
            }

            if (string.IsNullOrWhiteSpace(item.Approval.Status))
            {
                return "N/A";
            }

            if (string.IsNullOrWhiteSpace(item.Approval.ReviewStageName))
            {
                return item.Approval.Status;
            }

            return $"{item.Approval.Status} [{item.Approval.ReviewStageName}]";
        }
    }
