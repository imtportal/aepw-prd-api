        IXLWorksheet worksheet,
        int headerRow,
        int firstColumn,
        int lastColumn)
    {
      var headerRange =
          worksheet.Range(
              headerRow,
              firstColumn,
              headerRow,
              lastColumn
          );

      headerRange.Style.Font.Bold =
          true;

      headerRange.Style.Alignment.Horizontal =
          XLAlignmentHorizontalValues.Center;

      headerRange.Style.Alignment.Vertical =
          XLAlignmentVerticalValues.Center;

      headerRange.Style.Alignment.WrapText =
          true;

      headerRange.Style.Border.TopBorder =
          XLBorderStyleValues.Thin;

      headerRange.Style.Border.BottomBorder =
          XLBorderStyleValues.Thin;

      headerRange.Style.Border.LeftBorder =
          XLBorderStyleValues.Thin;

      headerRange.Style.Border.RightBorder =
          XLBorderStyleValues.Thin;

      // =========================================================
      // HEADER HEIGHT
      // =========================================================

      worksheet.Row(headerRow).Height =
          45;
    }


    // =============================================================
    // METRIC HEADER STYLE
    // =============================================================

    private static void ApplyMetricHeaderStyle(
        IXLCell cell,
        string backgroundColor,
        bool isTopLevel)
    {
      cell.Style.Fill.BackgroundColor =
          XLColor.FromHtml(
              backgroundColor
          );

      cell.Style.Font.Bold =
          true;

      // =========================================================
      // TOP LEVEL = WHITE TEXT
      // L1 = DARK TEXT
      // =========================================================

      cell.Style.Font.FontColor =
          isTopLevel
              ? XLColor.White
              : XLColor.Black;

      cell.Style.Alignment.Horizontal =
          XLAlignmentHorizontalValues.Center;

      cell.Style.Alignment.Vertical =
          XLAlignmentVerticalValues.Center;

      cell.Style.Alignment.WrapText =
          true;

      cell.Style.Border.TopBorder =
          XLBorderStyleValues.Thin;

      cell.Style.Border.BottomBorder =
          XLBorderStyleValues.Thin;

      cell.Style.Border.LeftBorder =
          XLBorderStyleValues.Thin;

      cell.Style.Border.RightBorder =
          XLBorderStyleValues.Thin;
    }


    // =============================================================
    // DATA FORMATTING
    // =============================================================

    private static void ApplyDataFormatting(
    IXLWorksheet worksheet,
    int startRow,
    int endRow,
    int yearColumn,
    int imIdColumn,
    int pinColumn,
    int imnameColumn,
    int contractPerformanceManagerColumn,
    int fundingRecipientColumn,
    int programColumn,
    int projectStatusColumn,
    int projectCategoryColumn,
    int cityColumn,
    int firstMetricColumn,
    int lastColumn)
    {
      // =========================================================
      // NO DATA
      // =========================================================

      if (endRow < startRow)
      {
        return;
      }


      // =========================================================
      // FULL DATA RANGE
      // =========================================================

      var dataRange =
          worksheet.Range(
              startRow,
              1,
              endRow,
              lastColumn
          );


      // =========================================================
      // GENERAL DATA FORMATTING
      // =========================================================

      dataRange.Style.Alignment.Vertical =
          XLAlignmentVerticalValues.Center;

      dataRange.Style.Border.TopBorder =
          XLBorderStyleValues.Thin;

      dataRange.Style.Border.BottomBorder =
          XLBorderStyleValues.Thin;

      dataRange.Style.Border.LeftBorder =
          XLBorderStyleValues.Thin;

      dataRange.Style.Border.RightBorder =
          XLBorderStyleValues.Thin;


      // =========================================================
      // ROW HEIGHT
      //
      // Increased from 22 so long text can be displayed.
      // =========================================================

      for (
          var row = startRow;
          row <= endRow;
          row++
      )
      {
        worksheet.Row(row).Height = 36;
      }


      // =========================================================
      // PROJECT COLUMN WIDTHS
      // =========================================================

      worksheet.Column(yearColumn).Width = 17;
      worksheet.Column(imIdColumn).Width = 18;
      worksheet.Column(pinColumn).Width = 17;
      worksheet.Column(imnameColumn).Width = 42;
      worksheet.Column(contractPerformanceManagerColumn).Width = 32;
      worksheet.Column(fundingRecipientColumn).Width = 25;
      worksheet.Column(programColumn).Width = 22;
      worksheet.Column(projectStatusColumn).Width = 22;
      worksheet.Column(projectCategoryColumn).Width = 24;
      worksheet.Column(cityColumn).Width = 22;


      // =========================================================
      // YEAR
      // =========================================================

      var yearRange =
          worksheet.Range(
              startRow,
              yearColumn,
              endRow,
              yearColumn
          );

      yearRange.Style.Alignment.Horizontal =
          XLAlignmentHorizontalValues.Center;

      yearRange.Style.Alignment.Vertical =
          XLAlignmentVerticalValues.Center;


      // =========================================================
      // IM ID
      // =========================================================

      var imIdRange =
          worksheet.Range(
              startRow,
              imIdColumn,
              endRow,
              imIdColumn
          );

      imIdRange.Style.Alignment.Horizontal =
          XLAlignmentHorizontalValues.Center;

      imIdRange.Style.Alignment.Vertical =
          XLAlignmentVerticalValues.Center;


      // =========================================================
      // PIN
      // =========================================================

      var pinRange =
          worksheet.Range(
              startRow,
              pinColumn,
              endRow,
              pinColumn
          );

      pinRange.Style.Alignment.Horizontal =
          XLAlignmentHorizontalValues.Center;

      pinRange.Style.Alignment.Vertical =
          XLAlignmentVerticalValues.Center;


      // =========================================================
      // LONG TEXT COLUMNS
      //
      // These columns should:
      //
      // 1. Wrap text
      // 2. Start from top
      // 3. Align left
      //
      // This prevents text from being cut/overlapped.
      // =========================================================

      var longTextColumns = new[]
      {
        imnameColumn,
        contractPerformanceManagerColumn,
        fundingRecipientColumn,
        programColumn,
        projectStatusColumn,
        projectCategoryColumn,
        cityColumn
    };


      foreach (var column in longTextColumns)
      {
        var range =
            worksheet.Range(
                startRow,
                column,
                endRow,
                column
            );

        range.Style.Alignment.WrapText =
            true;

        range.Style.Alignment.Vertical =
            XLAlignmentVerticalValues.Top;

        range.Style.Alignment.Horizontal =
            XLAlignmentHorizontalValues.Left;
      }


      // =========================================================
      // TITLE
      //
      // Extra protection for long project titles.
      // =========================================================

      worksheet.Range(
          startRow,
          imnameColumn,
          endRow,
          imnameColumn
      ).Style.Alignment.WrapText =
          true;


      // =========================================================
      // PROJECT MANAGER
      // =========================================================

      worksheet.Range(
          startRow,
          contractPerformanceManagerColumn,
          endRow,
          contractPerformanceManagerColumn
      ).Style.Alignment.WrapText =
          true;


      // =========================================================
      // FUNDING RECIPIENT
      // =========================================================

      worksheet.Range(
          startRow,
          fundingRecipientColumn,
          endRow,
          fundingRecipientColumn
      ).Style.Alignment.WrapText =
          true;


      // =========================================================
      // CITY
      // =========================================================

      worksheet.Range(
          startRow,
          cityColumn,
          endRow,
          cityColumn
      ).Style.Alignment.WrapText =
          true;


      // =========================================================
      // PROGRAM
      // =========================================================

      worksheet.Range(
          startRow,
          programColumn,
          endRow,
          programColumn
      ).Style.Alignment.WrapText =
          true;


      // =========================================================
      // PROJECT STATUS
      //
      // This is usually the longest text.
      // =========================================================

      worksheet.Range(
          startRow,
          projectStatusColumn,
          endRow,
          projectStatusColumn
      ).Style.Alignment.WrapText =
          true;


      // =========================================================
      // METRIC COLUMNS
      //
      // Risk Adjusted values and contribution percentages.
      // =========================================================

      for (
          var column = firstMetricColumn;
          column <= lastColumn;
          column++
      )
      {
        worksheet.Column(column).Width =
            15;

        var metricRange =
            worksheet.Range(
                startRow,
                column,
                endRow,
                column
            );

        metricRange.Style.Alignment.Horizontal =
            XLAlignmentHorizontalValues.Right;

        metricRange.Style.Alignment.Vertical =
            XLAlignmentVerticalValues.Center;
      }


      // =========================================================
      // IMPORTANT:
      // Do not change the background color of project data cells.
      //
      // Template/project-area colors remain untouched.
      // =========================================================


      // =========================================================
      // FONT
      //
      // Keep data readable but not overly bold.
      // =========================================================

      dataRange.Style.Font.Bold = false;


      // =========================================================
      // TOTAL ROW IS FORMATTED SEPARATELY
      //
      // ApplyTotalRowFormatting() handles the total row.
      // =========================================================
    }


    // =============================================================
    // TOTAL ROW FORMATTING
    // =============================================================

    private static void ApplyTotalRowFormatting(
        IXLWorksheet worksheet,
        int totalRow,
        int firstColumn,
        int lastColumn)
    {
      var totalRange =
          worksheet.Range(
              totalRow,
              firstColumn,
              totalRow,
              lastColumn
          );

      // =========================================================
      // LIGHT HIGHLIGHT
      // =========================================================

      totalRange.Style.Fill.BackgroundColor =
          XLColor.FromHtml(
              "#DCEAF2"
          );

      totalRange.Style.Font.Bold =
          true;

      totalRange.Style.Alignment.Vertical =
          XLAlignmentVerticalValues.Center;

      totalRange.Style.Border.TopBorder =
          XLBorderStyleValues.Medium;

      totalRange.Style.Border.BottomBorder =
          XLBorderStyleValues.Thin;

      totalRange.Style.Border.LeftBorder =
          XLBorderStyleValues.Thin;

      totalRange.Style.Border.RightBorder =
          XLBorderStyleValues.Thin;

      worksheet.Row(totalRow).Height =
          24;

      worksheet.Cell(
          totalRow,
          firstColumn
      ).Style.Alignment.Horizontal =
          XLAlignmentHorizontalValues.Center;
    }


    // =============================================================
    // TOP LEVEL CHECK
    // =============================================================

    private static bool IsTopLevelMetric(
        string metricCode)
    {
      if (string.IsNullOrWhiteSpace(
              metricCode))
      {
        return false;
      }

      var parts =
          metricCode.Split('.');

      // Example:
      //
      // MW1.1  -> Top Level
      // MW1.2  -> Top Level
      // MW1.3  -> Top Level
      //
      // MW1.11 -> L1
      // MW1.12 -> L1
      // MW1.21 -> L1

      if (parts.Length != 2)
      {
        return false;
      }

      return parts[1].Length == 1;
    }


    // =============================================================
    // CATEGORY COLOR
    //
    // Returns original SP color as string.
    //
    // Example:
    // #006699
    // =============================================================

    private static string GetCategoryColor(
        string? color)
    {
      if (string.IsNullOrWhiteSpace(
              color))
      {
        return "#7F8C8D";
      }

      var result =
          color.Trim();

      if (!result.StartsWith("#"))
      {
        result =
            "#" + result;
      }

      if (result.Length != 7)
      {
        return "#7F8C8D";
      }

      return result;
    }


    // =============================================================
    // DARKER COLOR
    //
    // Used for:
    //
    // Top Level
    // Top Level Contribution %
    // =============================================================

    private static string GetDarkerColor(
        string baseColor)
    {
      return AdjustColor(
          baseColor,
          0.70,
          false
      );
    }


    // =============================================================
    // LIGHTER COLOR
    //
    // Used for:
    //
    // L1 Metrics
    // =============================================================

    private static string GetLighterColor(
        string baseColor)
    {
      return AdjustColor(
          baseColor,
          0.78,
          true
      );
    }


    // =============================================================
    // COLOR ADJUSTMENT
    //
    // lighten = false
    //     Makes color darker.
    //
    // lighten = true
    //     Makes color lighter by moving toward white.
    // =============================================================

    private static string AdjustColor(
        string hex,
        double factor,
        bool lighten = false)
    {
      if (string.IsNullOrWhiteSpace(
              hex))
      {
        return "#7F8C8D";
      }

      hex =
          hex
              .Trim()
              .TrimStart('#');

      if (hex.Length != 6)
      {
        return "#7F8C8D";
      }


      // =========================================================
      // RED
      // =========================================================

      if (!int.TryParse(
              hex.Substring(
                  0,
                  2
              ),
              System.Globalization.NumberStyles.HexNumber,
              null,
              out var r))
      {
        return "#7F8C8D";
      }


      // =========================================================
      // GREEN
      // =========================================================

      if (!int.TryParse(
              hex.Substring(
                  2,
                  2
              ),
              System.Globalization.NumberStyles.HexNumber,
              null,
              out var g))
      {
        return "#7F8C8D";
      }


      // =========================================================
      // BLUE
      // =========================================================

      if (!int.TryParse(
              hex.Substring(
                  4,
                  2
              ),
              System.Globalization.NumberStyles.HexNumber,
              null,
              out var b))
      {
        return "#7F8C8D";
      }


      // =========================================================
      // LIGHTEN
      //
      // Move RGB values toward 255.
      // =========================================================

      if (lighten)
      {
        r =
            (int)(
                r +
                ((255 - r) * factor)
            );

        g =
            (int)(
                g +
                ((255 - g) * factor)
            );

        b =
            (int)(
                b +
                ((255 - b) * factor)
            );
      }
      else
      {
        // =====================================================
        // DARKEN
        //
        // Move RGB values toward 0.
        // =====================================================

        r =
            (int)(
                r * factor
            );

        g =
            (int)(
                g * factor
            );

        b =
            (int)(
                b * factor
            );
      }


      r =
          Math.Clamp(
              r,
              0,
              255
          );

      g =
          Math.Clamp(
              g,
              0,
              255
          );

      b =
          Math.Clamp(
              b,
              0,
              255
          );


      return
          $"#{r:X2}{g:X2}{b:X2}";
    }


    // =============================================================
    // DECIMAL VALUE
    // =============================================================

    private static void SetDecimalValue(
        IXLCell cell,
        decimal? value)
    {
      if (value.HasValue)
      {
        cell.Value =
            value.Value;

        cell.Style.NumberFormat.Format =
            "#,##0.000";

        cell.Style.Alignment.Horizontal =
            XLAlignmentHorizontalValues.Right;
      }
      else
      {
        cell.Value =
            "-";

        cell.Style.Alignment.Horizontal =
            XLAlignmentHorizontalValues.Center;
      }
    }


    // =============================================================
    // PERCENTAGE VALUE
    //
    // Input:
    // 25
    //
    // Excel value:
    // 0.25
    //
    // Display:
    // 25%
    // =============================================================

    private static void SetPercentageValue(
        IXLCell cell,
        decimal? value)
    {
      if (value.HasValue)
      {
        cell.Value =
            value.Value / 100m;

        cell.Style.NumberFormat.Format =
            "0.000%";

        cell.Style.Alignment.Horizontal =
            XLAlignmentHorizontalValues.Right;
      }
      else
      {
        cell.Value =
            "-";

        cell.Style.Alignment.Horizontal =
            XLAlignmentHorizontalValues.Center;
      }
    }


    // =============================================================
    // CLEAR OLD DATA
    // =============================================================

    private static void ClearDataContents(
        IXLWorksheet worksheet,
        int startRow,
        int lastColumn)
    {
      var lastExistingRow =
          worksheet.LastRowUsed()
              ?.RowNumber()
          ?? startRow;

      if (lastExistingRow >= startRow)
      {
        worksheet
            .Range(
                startRow,
                1,
                lastExistingRow,
                lastColumn
            )
            .Clear(
                XLClearOptions.Contents
            );
      }
    }


    // =============================================================
    // AUTO FILTER
    // =============================================================

    private static void ApplyAutoFilter(
        IXLWorksheet worksheet,
        int headerRow,
        int lastDataRow,
        int lastColumn)
    {
      if (lastDataRow <
          headerRow + 1)
      {
        return;
      }

      worksheet
          .Range(
              headerRow,
              1,
              lastDataRow,
              lastColumn
          )
          .SetAutoFilter();
    }


