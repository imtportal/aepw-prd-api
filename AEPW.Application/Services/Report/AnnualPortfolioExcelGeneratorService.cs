using ClosedXML.Excel;
using AEPW.Application.DTOs.Report.AnnualPortfolio;
using Microsoft.AspNetCore.Hosting;

namespace AEPW.Application.Services.Report
{
  public class AnnualPortfolioExcelGeneratorService
  {
    private readonly IWebHostEnvironment _environment;

    public AnnualPortfolioExcelGeneratorService(
        IWebHostEnvironment environment)
    {
      _environment = environment;
    }

    public byte[] GenerateAnnualPortfolioExcel(
        AnnualPortfolioRiskAdjustedReportDto report)
    {
      // =========================================================
      // TEMPLATE PATH
      // =========================================================

      var templatePath = Path.Combine(
          _environment.ContentRootPath,
          "Templates",
          "Report",
          "Risk-adjusted Portfolio.xlsx"
      );

      if (!File.Exists(templatePath))
      {
        throw new FileNotFoundException(
            "Risk-adjusted Excel template was not found.",
            templatePath
        );
      }

      using var workbook =
          new XLWorkbook(templatePath);

      var worksheet =
          workbook.Worksheets.FirstOrDefault();

      if (worksheet == null)
      {
        throw new InvalidOperationException(
            "Annual Portfolio template does not contain a worksheet."
        );
      }

      // =========================================================
      // ROW / COLUMN CONFIGURATION
      // =========================================================

      const int metadataRow = 1;
      const int headerRow = 2;
      const int dataStartRow = 3;

      // Project information columns (match redesigned template)
      const int yearColumn = 1;                       // A
      const int imIdColumn = 2;                       // B
      const int pinColumn = 3;                        // C
      const int imnameColumn = 4;                     // D
      const int contractPerformanceManagerColumn = 5; // E
      const int fundingRecipientColumn = 6;           // F
      const int programColumn = 7;                    // G
      const int projectStatusColumn = 8;              // H
      const int projectCategoryColumn = 9;             // I
      const int cityColumn = 10;                      // J

      // First metric starts from column K (11)
      const int firstMetricColumn = 11;

      // =========================================================
      // PROJECT ORDER
      //
      // Same project together:
      //
      // B005 - 2025
      // B005 - 2024
      // B006 - 2025
      // B006 - 2024
      // =========================================================

      //var projects =
      //    report.Projects
      //        .OrderBy(x => x.Pin)
      //        .ThenBy(x => x.ImId)
      //        .ThenByDescending(x => x.Year)
      //        .ToList();

      var projects =
    report.Projects?
        .OrderBy(x => x.Pin)
        .ThenBy(x => x.ImId)
        .ThenByDescending(x => x.Year)
        .ToList()
    ?? new List<AnnualPortfolioProjectDto>();

      // =========================================================
      // METRIC COLUMNS
      // =========================================================

      var categories =
          report.MetricCategories
              .OrderBy(x => x.DisplayOrder)
              .ToList();

      var metricColumns =
          BuildMetricColumns(
              worksheet,
              categories,
              headerRow,
              firstMetricColumn
          );

      // =========================================================
      // REPORT GENERATION METADATA (ROW 1)
      // =========================================================

      var generatedBy = report.GenerationDataDto?.GeneratedByUser;
      var generationDate = report.GenerationDataDto == null
          ? DateTime.MinValue
          : report.GenerationDataDto.GenerationDate;

      var generatedText =
          $"Generated by {(string.IsNullOrWhiteSpace(generatedBy) ? "Unknown" : generatedBy)} on {(generationDate == DateTime.MinValue ? "-" : generationDate.ToString("dd/MM/yyyy"))}";

      worksheet.Cell(metadataRow, 1).Value = generatedText;
      worksheet.Cell(metadataRow, 1).Style.Font.Bold = true;
      worksheet.Cell(metadataRow, 1).Style.Alignment.Horizontal =
          XLAlignmentHorizontalValues.Left;
      worksheet.Cell(metadataRow, 1).Style.Alignment.Vertical =
          XLAlignmentVerticalValues.Center;
      worksheet.Row(metadataRow).Height = 22;

      // =========================================================
      // CLEAR OLD DATA
      // =========================================================

      ClearDataContents(
          worksheet,
          dataStartRow,
          metricColumns.LastColumn
      );


      // =========================================================
      // CHECK WHETHER DATA IS AVAILABLE
      // =========================================================

      if (projects.Count == 0)
      {
        const int templateRow = dataStartRow;

        // Merge across the complete report width.
        var lastColumn = Math.Max(
            metricColumns.LastColumn,
            cityColumn
        );

        var messageRange = worksheet.Range(
            templateRow,
            1,
            templateRow,
            lastColumn
        );

        if (!messageRange.IsMerged())
        {
          messageRange.Merge();
        }

        worksheet.Cell(templateRow, 1).Value =
            "No data available for the selected filters";

        worksheet.Cell(templateRow, 1).Style.Alignment.Horizontal =
            XLAlignmentHorizontalValues.Center;

        worksheet.Cell(templateRow, 1).Style.Alignment.Vertical =
            XLAlignmentVerticalValues.Center;

        worksheet.Cell(templateRow, 1).Style.Alignment.WrapText = true;

        worksheet.Cell(templateRow, 1).Style.Font.Bold = true;

        worksheet.Row(templateRow).Height = 30;

        // Generate Excel with the no-data message.
        using var emptyStream = new MemoryStream();

        workbook.SaveAs(emptyStream);

        return emptyStream.ToArray();
      }

      // =========================================================
      // PROJECT HEADER FORMATTING
      // =========================================================

      ApplyProjectHeaderFormatting(
          worksheet,
          headerRow,
          yearColumn,
          imIdColumn,
          pinColumn,
          imnameColumn,
          contractPerformanceManagerColumn,
          fundingRecipientColumn,
          programColumn,
          projectStatusColumn,
          projectCategoryColumn,
          cityColumn
      );

      // =========================================================
      // METRIC HEADER FORMATTING
      // =========================================================

      ApplyHeaderFormatting(
          worksheet,
          headerRow,
          firstMetricColumn,
          metricColumns.LastColumn
      );

      // =========================================================
      // WRITE PROJECT DATA
      // =========================================================

      var currentRow = dataStartRow;

      foreach (var project in projects)
      {
        // =====================================================
        // PROJECT INFORMATION
        // =====================================================

        worksheet.Cell(
            currentRow,
            yearColumn
        ).Value =
            project.Year ?? "-";


        worksheet.Cell(
            currentRow,
            imIdColumn
        ).Value =
            project.ImId ?? "-";


        worksheet.Cell(
            currentRow,
            pinColumn
        ).Value =
            project.Pin ?? "-";


        worksheet.Cell(
            currentRow,
            imnameColumn
        ).Value =
            project.ProjectTitle ?? "-";


        worksheet.Cell(
            currentRow,
            contractPerformanceManagerColumn
        ).Value =
            project.ProjectManager ?? "-";


        worksheet.Cell(
            currentRow,
            fundingRecipientColumn
        ).Value =
            project.FundingRecipient ?? "-";


        worksheet.Cell(
            currentRow,
            programColumn
        ).Value =
            project.Program ?? "-";


        worksheet.Cell(
            currentRow,
            projectStatusColumn
        ).Value =
            project.ProjectStatus ?? "-";


        worksheet.Cell(
            currentRow,
            projectCategoryColumn
        ).Value =
            project.ProjectCategory ?? "-";


        worksheet.Cell(
            currentRow,
            cityColumn
        ).Value =
            project.City ?? "-";


        // =====================================================
        // METRIC VALUES
        //
        // Each project object represents:
        //
        // ImpactMasterId + Year
        //
        // Therefore values are year specific.
        // =====================================================

        foreach (var metricColumn in metricColumns.Columns)
        {
          var metricCell =
              worksheet.Cell(
                  currentRow,
                  metricColumn.ColumnNumber
              );

          if (project.MetricValues.TryGetValue(
                  metricColumn.MetricCode,
                  out var metricValue) &&
              metricValue != null)
          {
            // =================================================
            // RISK ADJUSTED
            // =================================================

            SetDecimalValue(
                metricCell,
                metricValue.RiskAdjusted
            );


            // =================================================
            // CONTRIBUTION %
            //
            // Only Top Level metrics have contribution.
            // =================================================

            if (metricColumn.IsTopLevel)
            {
              var contributionCell =
                  worksheet.Cell(
                      currentRow,
                      metricColumn.ColumnNumber + 1
                  );

              SetPercentageValue(
                  contributionCell,
                  metricValue.ContributionPercentage
              );
            }
          }
          else
          {
            SetDecimalValue(
                metricCell,
                null
            );

            if (metricColumn.IsTopLevel)
            {
              worksheet.Cell(
                  currentRow,
                  metricColumn.ColumnNumber + 1
              ).Value = "-";
            }
          }
        }

        currentRow++;
      }

      var lastProjectRow =
          currentRow - 1;

      // =========================================================
      // DATA FORMATTING
      // =========================================================

      ApplyDataFormatting(
          worksheet,
          dataStartRow,
          lastProjectRow,
          yearColumn,
          imIdColumn,
          pinColumn,
          imnameColumn,
          contractPerformanceManagerColumn,
          fundingRecipientColumn,
          programColumn,
          projectStatusColumn,
          projectCategoryColumn,
          cityColumn,
          firstMetricColumn,
          metricColumns.LastColumn
      );

      // =========================================================
      // AUTO FILTER
      // =========================================================

      ApplyAutoFilter(
          worksheet,
          headerRow,
          lastProjectRow,
          metricColumns.LastColumn
      );

      // =========================================================
      // TOTAL ROW
      //
      // report.Totals:
      //
      // MW1.1 -> Grand Total across ALL selected years
      // MW1.2 -> Grand Total across ALL selected years
      //
      // Top-level contribution = 100%
      // =========================================================

      var totalRow = currentRow;

      worksheet.Cell(
          totalRow,
          yearColumn
      ).Value = "Total";


      // Clear project information in total row
      for (
          var column = imIdColumn;
          column < firstMetricColumn;
          column++
      )
      {
        worksheet.Cell(
            totalRow,
            column
        ).Value = "";
      }


      // =========================================================
      // TOTAL METRICS
      // =========================================================

      foreach (var metricColumn in metricColumns.Columns)
      {
        var totalCell =
            worksheet.Cell(
                totalRow,
                metricColumn.ColumnNumber
            );

        if (report.Totals.TryGetValue(
                metricColumn.MetricCode,
                out var totalValue) &&
            totalValue != null)
        {
          // =================================================
          // GRAND TOTAL RISK ADJUSTED
          // =================================================

          SetDecimalValue(
              totalCell,
              totalValue.RiskAdjusted
          );


          // =================================================
          // GRAND TOTAL CONTRIBUTION
          //
          // Grand total itself = 100%
          // =================================================

          if (metricColumn.IsTopLevel)
          {
            var contributionCell =
                worksheet.Cell(
                    totalRow,
                    metricColumn.ColumnNumber + 1
                );

            SetPercentageValue(
                contributionCell,
                totalValue.RiskAdjusted.HasValue
                    ? 100m
                    : null
            );
          }
        }
        else
        {
          SetDecimalValue(
              totalCell,
              null
          );

          if (metricColumn.IsTopLevel)
          {
            worksheet.Cell(
                totalRow,
                metricColumn.ColumnNumber + 1
            ).Value = "-";
          }
        }
      }

      // =========================================================
      // TOTAL ROW FORMATTING
      // =========================================================

      ApplyTotalRowFormatting(
          worksheet,
          totalRow,
          yearColumn,
          metricColumns.LastColumn
      );

      // =========================================================
      // FREEZE HEADER
      // =========================================================

      //worksheet.SheetView.FreezeRows(2);

      // =========================================================
      // SAVE
      // =========================================================

      using var stream =
          new MemoryStream();

      workbook.SaveAs(stream);

      return stream.ToArray();
    }


    // =============================================================
    // BUILD METRIC COLUMNS
    // =============================================================

    private static MetricColumnResult BuildMetricColumns(
        IXLWorksheet worksheet,
        List<AnnualPortfolioMetricCategoryDto> categories,
        int headerRow,
        int firstMetricColumn)
    {
      var columns =
          new List<MetricColumnInfo>();

      var currentColumn =
          firstMetricColumn;

      foreach (var category in categories)
      {
        // =====================================================
        // GET ORIGINAL CATEGORY COLOR
        // =====================================================

        var baseColor =
            GetCategoryColor(
                category.Color
            );

        // =====================================================
        // TOP LEVEL = DARK SHADE
        // =====================================================

        var topLevelColor =
            GetDarkerColor(
                baseColor
            );

        // =====================================================
        // L1 = LIGHT SHADE
        // =====================================================

        var l1Color =
            GetLighterColor(
                baseColor
            );


        foreach (var metric in category.Metrics)
        {
          var metricCode =
              metric.MetricCode;

          var isTopLevel =
              IsTopLevelMetric(
                  metricCode
              );

          // =================================================
          // METRIC HEADER
          // =================================================

          var metricCell =
              worksheet.Cell(
                  headerRow,
                  currentColumn
              );

          metricCell.Value =
              metricCode;

          ApplyMetricHeaderStyle(
              metricCell,
              isTopLevel
                  ? topLevelColor
                  : l1Color,
              isTopLevel
          );

          columns.Add(
              new MetricColumnInfo
              {
                MetricCode =
                      metricCode,

                ColumnNumber =
                      currentColumn,

                IsTopLevel =
                      isTopLevel
              }
          );

          currentColumn++;


          // =================================================
          // TOP LEVEL CONTRIBUTION COLUMN
          // =================================================

          if (isTopLevel)
          {
            var contributionCell =
                worksheet.Cell(
                    headerRow,
                    currentColumn
                );

            contributionCell.Value =
                $"{metricCode} contribution (%)";

            ApplyMetricHeaderStyle(
                contributionCell,
                topLevelColor,
                true
            );

            currentColumn++;
          }
        }
      }

      return new MetricColumnResult
      {
        Columns = columns,

        LastColumn =
              currentColumn - 1
      };
    }


    // =============================================================
    // PROJECT HEADER FORMATTING
    // =============================================================

    private static void ApplyProjectHeaderFormatting(
     IXLWorksheet worksheet,
     int headerRow,
     int yearColumn,
     int imIdColumn,
     int pinColumn,
     int imnameColumn,
     int contractPerformanceManagerColumn,
     int fundingRecipientColumn,
     int programColumn,
     int projectStatusColumn,
     int projectCategoryColumn,
     int cityColumn)
    {
      var columns = new[]
      {
        yearColumn,
        imIdColumn,
        pinColumn,
        imnameColumn,
        contractPerformanceManagerColumn,
        fundingRecipientColumn,
        programColumn,
        projectStatusColumn,
        projectCategoryColumn,
        cityColumn
    };

      foreach (var column in columns)
      {
        var cell =
            worksheet.Cell(
                headerRow,
                column
            );

        cell.Style.Font.Bold = true;

        cell.Style.Alignment.Horizontal =
            XLAlignmentHorizontalValues.Center;

        cell.Style.Alignment.Vertical =
            XLAlignmentVerticalValues.Center;

        cell.Style.Alignment.WrapText = true;

        // IMPORTANT:
        // Do NOT set background color here.
        // Template's original grey color will remain.

        cell.Style.Border.TopBorder =
            XLBorderStyleValues.Thin;

        cell.Style.Border.BottomBorder =
            XLBorderStyleValues.Thin;

        cell.Style.Border.LeftBorder =
            XLBorderStyleValues.Thin;

        cell.Style.Border.RightBorder =
            XLBorderStyleValues.Thin;
      }
    }

    // =============================================================
    // GENERAL HEADER FORMATTING
    // =============================================================

