
using ClosedXML.Excel;
using AEPW.Application.DTOs.Report.Summary;
using Microsoft.AspNetCore.Hosting;

namespace AEPW.Application.Services.Report
{
  public class SummaryExcelGeneratorService
  {
    private readonly IWebHostEnvironment _environment;

    public SummaryExcelGeneratorService(
        IWebHostEnvironment environment)
    {
      _environment = environment;
    }

    public MemoryStream GenerateSummaryExcel(
        SummaryReportDto report)
    {
      // 1. Locate redesigned template
      var templatePath = Path.Combine(
          _environment.ContentRootPath,
          "Templates",
          "Report",
          "Summary_API_Template.xlsx"
      );

      if (!File.Exists(templatePath))
      {
        throw new FileNotFoundException(
            "Summary Excel template was not found.",
            templatePath
        );
      }

      // 2. Open template
      using var workbook = new XLWorkbook(templatePath);

      var worksheet = workbook.Worksheet("Summary");

      // 3. Populate report information
      PopulateReportInformation(worksheet, report);

      // 4. Get all available years
      var years = GetYears(report);

      if (years.Count > 0)
      {
        // 5. Setup dynamic year columns
        SetupYearColumns(worksheet, years);

        // 6. Populate metric rows
        PopulateMetricRows(worksheet, report, years);
      }


      // Apply 3 decimal places to numeric report cells.
      int lastRow = worksheet.LastRowUsed()?.RowNumber() ?? 7;
      int lastColumn = worksheet.LastColumnUsed()?.ColumnNumber() ?? 6;

      for (int row = 8; row <= lastRow; row++)
      {
        for (int column = 5; column <= lastColumn; column++)
        {
          worksheet.Cell(row, column)
              .Style.NumberFormat.Format = "#,##0.000";
        }
      }

      // 7. Save workbook to memory
      var stream = new MemoryStream();

      workbook.SaveAs(stream);
      stream.Position = 0;

      return stream;
    }

    // =============================================================
    // REPORT INFORMATION
    // =============================================================

    private void PopulateReportInformation(
        IXLWorksheet worksheet,
        SummaryReportDto report)
    {
      var filters = report.Filters;

      // A1 = Generated by username and generation date
      var generatedBy =
          filters.GeneratedByUser ?? string.Empty;

      var generatedDate =
          filters.GenerationDate;

      var dateText =
          generatedDate == DateTime.MinValue
              ? string.Empty
              : generatedDate.ToString("dd/MM/yyyy");

      worksheet.Cell("A1").Value =
          $"Generated by {generatedBy} on {dateText}";

      // Redesigned template: project values are in column B
      worksheet.Cell("B3").Value =
          JoinValues(filters.ProjectPIN);

      worksheet.Cell("B4").Value =
          JoinValues(filters.ProjectName);
    }

    private static string JoinValues<T>(
        List<T>? values)
    {
      if (values == null || values.Count == 0)
      {
        return string.Empty;
      }

      return string.Join(", ", values);
    }

    // =============================================================
    // GET YEARS
    // =============================================================

    private List<int> GetYears(
        SummaryReportDto report)
    {
      var years = new List<int>();

      foreach (var data in report.Data)
      {
        // Normal metric yearly values
        if (data.YearlyRiskAdjustedValues != null)
        {
          years.AddRange(
              data.YearlyRiskAdjustedValues
                  .Select(x => x.Year)
          );
        }

        // MC SUM_L1 summary yearly values
        if (data.Summary?.YearlyRiskAdjustedValues != null)
        {
          years.AddRange(
              data.Summary.YearlyRiskAdjustedValues
                  .Select(x => x.Year)
          );
        }

        // MC L1 yearly values
        if (data.L1Metrics != null)
        {
          foreach (var l1Metric in data.L1Metrics)
          {
            if (l1Metric.YearlyRiskAdjustedValues != null)
            {
              years.AddRange(
                  l1Metric.YearlyRiskAdjustedValues
                      .Select(x => x.Year)
              );
            }
          }
        }
      }

      return years
          .Distinct()
          .OrderByDescending(x => x)
          .ToList();
    }

    // =============================================================
    // YEAR COLUMNS
    // Header row = 7
    // Latest year = F
    // Previous years = G onward
    // =============================================================

    private void SetupYearColumns(
        IXLWorksheet worksheet,
        List<int> years)
    {
      if (years.Count == 0)
      {
        return;
      }

      int latestYear = years.First();

      // F7 = Total for latest year
      worksheet.Cell("F7").Value =
          $"Total for {latestYear}";

      var previousYears = years.Skip(1).ToList();

      const int firstYearColumn = 7; // G

      // Clear the first previous-year header if no previous year
      if (previousYears.Count == 0)
      {
        worksheet.Cell(7, firstYearColumn).Clear(
            (XLClearOptions)XLCellsUsedOptions.Contents
        );
      }

      for (int i = 0; i < previousYears.Count; i++)
      {
        int columnNumber = firstYearColumn + i;

        // G already exists in the template.
        // Copy G formatting for H, I, J, etc.
        if (columnNumber > firstYearColumn)
        {
          worksheet.Column(firstYearColumn)
              .CopyTo(worksheet.Column(columnNumber));
        }

        worksheet.Cell(7, columnNumber).Value =
            previousYears[i];
      }
    }

    // =============================================================
    // METRIC ROWS
    // Data starts at row 8
    // =============================================================

    private void PopulateMetricRows(
        IXLWorksheet worksheet,
        SummaryReportDto report,
        List<int> years)
    {
      const int templateRow = 8;

      int currentRow = templateRow;

      // Store first and last row for each topic
      var topicRanges =
          new Dictionary<string, (int StartRow, int EndRow)>();

      foreach (var category in report.Data)
      {
        int categoryStartRow = currentRow;

        // Top-level metric
        PopulateTopLevelMetric(
            worksheet,
            templateRow,
            currentRow,
            category,
            years
        );

        currentRow++;

        // MC L1 metrics
        if (category.CategoryCode == "MC" &&
            category.L1Metrics != null)
        {
          foreach (var l1Metric in category.L1Metrics)
          {
            PopulateL1Metric(
                worksheet,
                templateRow,
                currentRow,
                category,
                l1Metric,
                years
            );

            currentRow++;
          }
        }

        int categoryEndRow = currentRow - 1;

        // Combine rows belonging to the same topic
        string topicKey = category.CategoryCode;

        if (topicRanges.ContainsKey(topicKey))
        {
          var existing = topicRanges[topicKey];

          topicRanges[topicKey] = (
              existing.StartRow,
              categoryEndRow
          );
        }
        else
        {
          topicRanges[topicKey] = (
              categoryStartRow,
              categoryEndRow
          );
        }
      }

      // Merge each topic cell
      foreach (var topic in topicRanges)
      {
        MergeTopicCells(
            worksheet,
            topic.Value.StartRow,
            topic.Value.EndRow
        );
      }
    }

    // =============================================================
    // TOP-LEVEL METRIC
    // A = Topic
    // B = Metric Code
    // C = Metric Name
    // D = Unit
    // E = Since Inception
    // F = Latest year
    // G onward = Previous years
    // =============================================================

    private void PopulateTopLevelMetric(
        IXLWorksheet worksheet,
        int templateRow,
        int targetRow,
        SummaryDataDto data,
        List<int> years)
    {
      CopyRowFormatting(
          worksheet,
          templateRow,
          targetRow
      );

      // A = Topic
      worksheet.Cell(targetRow, 1).Value =
          data.CategoryName ?? string.Empty;

      // B = Top-level metric code
      worksheet.Cell(targetRow, 2).Value =
          data.TopLevelMetric?.MetricCode ?? string.Empty;

      // C = Top-level metric name
      worksheet.Cell(targetRow, 3).Value =
          data.TopLevelMetric?.MetricName ?? string.Empty;

      // D = Unit
      worksheet.Cell(targetRow, 4).Value =
          data.TopLevelMetric?.Unit ?? string.Empty;

      // E = Total since inception
      // MC uses SUM_L1 summary
      if (data.CategoryCode == "MC" &&
          data.Summary != null)
      {
        worksheet.Cell(targetRow, 5).Value =
            data.Summary.TotalSinceInception;

        PopulateYearValues(
            worksheet,
            targetRow,
            data.Summary.YearlyRiskAdjustedValues,
            years
        );
      }
      else
      {
        worksheet.Cell(targetRow, 5).Value =
            data.TotalSinceInception;

        PopulateYearValues(
            worksheet,
            targetRow,
            data.YearlyRiskAdjustedValues,
            years
        );
      }
    }

    // =============================================================
    // MC L1 METRIC
    // =============================================================

    private void PopulateL1Metric(
        IXLWorksheet worksheet,
        int templateRow,
        int targetRow,
        SummaryDataDto category,
        SummaryL1MetricDto l1Metric,
        List<int> years)
    {
      CopyRowFormatting(
          worksheet,
          templateRow,
          targetRow
      );

      // A = Topic
      worksheet.Cell(targetRow, 1).Value =
          category.CategoryName ?? string.Empty;

      // B = L1 metric code
      worksheet.Cell(targetRow, 2).Value =
          l1Metric.MetricCode ?? string.Empty;

      // C = L1 metric description
      worksheet.Cell(targetRow, 3).Value =
          l1Metric.MetricName ?? string.Empty;

      // Preserve blue formatting for MC L1 metrics
      worksheet.Cell(targetRow, 2)
          .Style.Font.FontColor = XLColor.Blue;

      worksheet.Cell(targetRow, 3)
          .Style.Font.FontColor = XLColor.Blue;

      // D = Unit
      worksheet.Cell(targetRow, 4).Value =
          l1Metric.Unit ?? string.Empty;

      // E = Total since inception
      worksheet.Cell(targetRow, 5).Value =
          l1Metric.TotalSinceInception;

      // F onward = yearly values
      PopulateYearValues(
          worksheet,
          targetRow,
          l1Metric.YearlyRiskAdjustedValues,
          years
      );

      // Indent MC L1 metric code
      worksheet.Cell(targetRow, 2)
          .Style.Alignment.Indent = 1;
    }

    // =============================================================
    // YEARLY VALUES
    // Latest year = F (6)
    // Previous years = G (7) onward
    // =============================================================

    private void PopulateYearValues(
        IXLWorksheet worksheet,
        int row,
        List<YearlyValueDto>? yearlyValues,
        List<int> years)
    {
      if (years.Count == 0)
      {
        return;
      }

      var valuesByYear = yearlyValues?
          .GroupBy(x => x.Year)
          .ToDictionary(
              x => x.Key,
              x => x.First().Value
          ) ?? new Dictionary<int, decimal>();

      // Latest year -> F
      int latestYear = years.First();

      worksheet.Cell(row, 6).Value =
          valuesByYear.TryGetValue(
              latestYear,
              out var latestValue)
              ? latestValue
              : 0;

      // Previous years -> G onward
      var previousYears = years.Skip(1).ToList();

      for (int i = 0; i < previousYears.Count; i++)
      {
        int columnNumber = 7 + i;

        worksheet.Cell(row, columnNumber).Value =
            valuesByYear.TryGetValue(
                previousYears[i],
                out var value)
                ? value
                : 0;
      }
    }

    // =============================================================
    // COPY TEMPLATE ROW FORMATTING
    // =============================================================

    private void CopyRowFormatting(
        IXLWorksheet worksheet,
        int templateRow,
        int targetRow)
    {
      if (templateRow == targetRow)
      {
        return;
      }

      worksheet.Row(templateRow)
          .CopyTo(worksheet.Row(targetRow));
    }

    // =============================================================
    // MERGE TOPIC CELLS
    // Topic is now in column A
    // =============================================================

    private void MergeTopicCells(
        IXLWorksheet worksheet,
        int startRow,
        int endRow)
    {
      if (startRow >= endRow)
      {
        return;
      }

      var range = worksheet.Range(
          startRow,
          1, // Column A = Topic
          endRow,
          1
      );

      range.Merge();

      range.Style.Alignment.Vertical =
          XLAlignmentVerticalValues.Center;

      range.Style.Alignment.Horizontal =
          XLAlignmentHorizontalValues.Left;

      range.Style.Alignment.WrapText = true;
    }
  }
}
